// Navegador real automatizado; no acredita un teclado Android físico.
// Servidor dedicado 8771. npm/Playwright solo pertenecen al entorno de QA.
const assert = require("node:assert/strict");
const { chromium } = require("playwright");
const origen = process.env.CBL_QA_ORIGIN || "http://127.0.0.1:8771";
async function ejecutar() {
  const browser = await chromium.launch({ executablePath: process.env.CBL_CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
  let checks = 0;
  const eq = (a,b,m) => { assert.deepEqual(a,b,m); checks++; console.log("OK " + checks + ": " + m); };
  const errores = [], externas = [];
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 } });
  await context.route("**/*", route => { const u = route.request().url(); if (/^https?:/.test(u) && !u.startsWith(origen)) { externas.push(u); return route.abort(); } return route.continue(); });
  const page = await context.newPage(); page.on("pageerror", e => errores.push(e.message));
  const doc = () => page.evaluate(() => demoEditores[0].documento().texto);
  const poner = (texto,pos = 0) => page.evaluate(([texto,pos]) => { const c = demoEditores[0].codigo; c.value = texto; c.setSelectionRange(pos,pos); c.dispatchEvent(new Event("input")); },[texto,pos]);
  try {
    await page.goto(origen + "/shared/editor/demo.html");
    await page.waitForFunction(() => window.demoEditores?.length === 2);
    eq(await page.locator(".cm-editor").count(),2,"dos instancias independientes");
    eq(await page.evaluate(() => demoEditores.map(e=>e.codigo.getAttribute("aria-hidden"))),["true","true"],"puerto heredado fuera del árbol accesible");
    const segundo = await page.evaluate(() => demoEditores[1].documento().texto);
    await poner("let n = 1;",10);
    await page.locator("#demo-uno .cm-content").focus();
    await page.keyboard.type("\n"); // Enter real, incluido el camino de sangría heredado
    await page.keyboard.type("n += 2;");
    eq(await doc(),"let n = 1;\nn += 2;","Enter y escritura actualizan el documento");
    eq(await page.evaluate(() => demoEditores[0].codigo.value),await doc(),"puerto y documento sincronizados");
    eq(await page.evaluate(() => demoEditores[1].documento().texto),segundo,"editar no afecta al otro documento");
    await page.keyboard.press("Control+z");
    eq(await doc(),"let n = 1;","Ctrl+Z usa el historial de las barras");
    await page.keyboard.press("Control+Shift+z");
    eq(await doc(),"let n = 1;\nn += 2;","Ctrl+Shift+Z recorre el mismo historial");
    await page.evaluate(() => demoEditores[0].fachada.edicion.deshacer());
    eq(await doc(),"let n = 1;","botón de deshacer tras escritura real");
    await page.evaluate(() => demoEditores[0].fachada.edicion.rehacer());
    eq(await doc(),"let n = 1;\nn += 2;","botón de rehacer");
    await page.locator("#demo-uno .cm-content").focus(); await page.keyboard.press("Control+a");
    const cdp = await context.newCDPSession(page);
    await cdp.send("Input.imeSetComposition",{text:"composición",selectionStart:11,selectionEnd:11});
    await cdp.send("Input.insertText",{text:"composición"});
    eq(await doc(),"composición","composición IME de Chromium sincronizada");
    await context.grantPermissions(["clipboard-read","clipboard-write"]);
    const pegado = '// á 😀 <b>\nconst xs = [1, 2];\nconsole.log(xs);';
    await page.evaluate(t=>navigator.clipboard.writeText(t),pegado);
    await page.keyboard.press("Control+a"); await page.keyboard.press("Control+v");
    await page.waitForFunction(t=>demoEditores[0].documento().texto===t,pegado);
    eq(await doc(),pegado,"pegado multilínea y Unicode por portapapeles");
    await poner("const datos = [1, { n: 2 }];",14);
    await page.waitForTimeout(100);
    eq(await page.locator("#demo-uno .cm-matchingBracket").count(),2,"ambos delimitadores resaltados");
    const programa = 'function sumar(a, b) {\n  const texto = "á 😀 <b>";\n  return a + b;\n}\nconsole.log(sumar(1, 2));';
    await poner(programa);
    await page.waitForTimeout(100);
    await page.locator("#demo-uno .cm-foldGutter .cm-gutterElement").filter({hasText:"⌄"}).first().click();
    eq(await page.locator("#demo-uno .cm-foldPlaceholder").count(),1,"plegado desde el margen");
    eq(await doc(),programa,"plegar conserva texto, Unicode y líneas originales");
    await page.evaluate(() => demoEditores[0].irALinea(3));
    await page.waitForTimeout(100);
    eq(await page.locator("#demo-uno .cm-foldPlaceholder").count(),0,"ir a una línea oculta expande el bloque");
    eq(await page.evaluate(() => demoEditores[0].codigo.value.slice(demoEditores[0].codigo.selectionStart,demoEditores[0].codigo.selectionEnd)),"  return a + b;","navegación usa offsets originales");
    await page.locator('[data-demo="0"] [data-lectura]').check();
    eq(await page.locator("#demo-uno .cm-content").getAttribute("contenteditable"),"false","solo lectura llega al motor");
    eq(await page.evaluate(()=>demoEditores[0].insertar("NO")),false,"solo lectura bloquea inserción API");
    eq(await doc(),programa,"solo lectura conserva el programa");
    await page.locator('[data-demo="0"] [data-lectura]').uncheck();
    await poner("const = ;"); await page.waitForTimeout(900);
    eq(await page.locator("#demo-uno .cm-lintRange-error").count()>0,true,"diagnóstico de sintaxis en la línea afectada");
    await poner("console.log(1);"); await page.waitForTimeout(900);
    eq(await page.locator("#demo-uno .cm-lintRange-error").count(),0,"el diagnóstico desaparece al corregir");
    await page.locator('#demo-uno [data-editor="lenguaje"]').selectOption("python");
    await page.waitForFunction(() => demoEditores[0].documento().lenguaje === "python");
    await poner("if True:",8); await page.locator("#demo-uno .cm-content").focus();
    await page.keyboard.press("Enter"); await page.keyboard.type("print(1)");
    eq(await doc(),"if True:\n    print(1)","Enter respeta los cuatro espacios de Python");
    await page.waitForTimeout(900);
    eq(await page.locator("#demo-uno .cm-lintRange-error").count(),0,"Python válido sin falso diagnóstico");
    await poner("def generador():\n    yield\n"); await page.waitForTimeout(900);
    eq(await page.locator("#demo-uno .cm-lintRange-error").count(),0,"yield sin valor no produce el falso error de lezer");
    await page.locator('#demo-uno [data-editor="lenguaje"]').selectOption("js");
    eq(await doc(),"console.log(1);","cambiar de lenguaje recupera su documento");
    await page.locator('[data-demo="0"] [data-documento]').selectOption("borrador");
    await page.locator("#demo-uno .cm-content").focus(); await page.keyboard.press("Control+End"); await page.keyboard.type("let propio = 2;");
    const borrador = await doc();
    await page.locator('[data-demo="0"] [data-documento]').selectOption("principal");
    eq(await doc(),"console.log(1);","documentos conservan su texto");
    await page.locator('[data-demo="0"] [data-documento]').selectOption("borrador");
    eq(await doc(),borrador,"borrador conserva su texto");
    await page.locator('[data-demo="0"] [data-recrear]').click();
    eq(await page.locator(".cm-editor").count(),2,"recrear retira el motor anterior");
    eq(await doc(),borrador,"recrear conserva documento");
    await page.evaluate(() => demoEditores[0].fachada.edicion.activar(true));
    eq(await page.locator('#demo-uno [data-editor="bloques"]').isVisible(),true,"modo sin teclado conserva fichas");
    eq(await page.locator("#demo-uno .cm-editor").isVisible(),false,"el motor no se superpone a las fichas");
    await page.evaluate(() => { const c=demoEditores[0].codigo; c.setSelectionRange(0,0); demoEditores[0].insertar("// añadido\n"); });
    eq((await doc()).startsWith("// añadido\n"),true,"editar con fichas actualiza CodeMirror");
    await page.evaluate(() => demoEditores[0].fachada.edicion.deshacer());
    eq(await doc(),borrador,"historial compartido entre fichas y teclado");
    await page.evaluate(() => demoEditores[0].fachada.edicion.activar(false));
    eq(await page.locator("#demo-uno .cm-content").innerText(),borrador.trimEnd(),"volver al teclado conserva texto visible");
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('#demo-uno').dataset.forma==='movil');
    await page.locator("#demo-uno .cm-content").focus();
    eq(await page.evaluate(()=>demoEditores[0].fachada.tieneFoco()),true,"foco reconocido por la interfaz móvil");
    await page.locator('#demo-uno [data-editor="paleta"] .atajo').first().dispatchEvent("pointerdown",{pointerType:"touch",button:0});
    eq(await page.evaluate(()=>demoEditores[0].fachada.tieneFoco()),true,"tocar una herramienta conserva el foco");
    const largo = Array.from({length:1000},(_,i)=>`const n${i} = ${i};`).join('\n');
    await poner(largo);await page.waitForTimeout(150);
    eq(await doc(),largo,"documento grande íntegro");
    eq(await page.locator('#demo-uno .cm-line').count()<100,true,"solo renderiza una fracción visible del documento");
    await poner('console.log(1);');
    await page.locator('#demo-uno [data-editor="b-pantalla"]').click();
    eq(await page.evaluate(()=>Math.round(document.querySelector('#demo-uno').getBoundingClientRect().width)),390,"pantalla completa móvil");
    await page.keyboard.press("Escape");
    eq(await page.evaluate(()=>document.querySelector('#demo-uno').dataset.pantallaCompleta),"false","Escape restaura distribución");
    for (const serie of ["war","factory"]) {
      await page.goto(origen+"/Prototypes/Rocket%20Launcher/?forma=movil&serie="+serie);
      await page.waitForFunction(()=>window.__juegoListo);
      eq(await page.locator(".cm-editor").count(),1,serie+": motor integrado");
      await page.evaluate(()=>{cmg.seudo?.aplicarModo('js');cmg.edicion.activar(false);});
      if (serie === "war") {
        await page.evaluate(()=>{const c=cmg.codigo;c.value='const numeros = [1, 2, 3];\nconsole.log(numeros);';c.setSelectionRange(0,0);c.dispatchEvent(new Event("input"));});
        await page.locator(".cm-content").focus();
        const arrastrarPM = async () => {
          const p=page.locator('#edicion .protomouse');await p.scrollIntoViewIfNeeded();const r=await p.boundingBox();
          await page.mouse.move(r.x+r.width/2,r.y+r.height/2);await page.mouse.down();await page.mouse.move(r.x+r.width/2+30,r.y+r.height/2,{steps:8});await page.mouse.up();
        };
        await arrastrarPM();
        eq(await page.evaluate(()=>cmg.codigo.selectionStart>0),true,"ProtoMouse usa coordenadas de CodeMirror");
        eq(await page.evaluate(()=>cmg.editor.fachada.tieneFoco()),true,"ProtoMouse mantiene el foco de escritura");
        await page.locator('#edicion [data-seleccion]').click();await arrastrarPM();
        eq(await page.evaluate(()=>cmg.codigo.selectionEnd>cmg.codigo.selectionStart),true,"ProtoMouse amplía la selección");
        await page.evaluate(()=>{cmg.edicion.seleccion(false);document.activeElement.blur();});await arrastrarPM();
        eq(await page.evaluate(()=>cmg.editor.fachada.tieneFoco()),false,"ProtoMouse no abre el teclado cerrado");
        eq(await page.locator('.pm-cursor').isVisible(),true,"cursor propio visible sin foco");
      }
      await page.evaluate(()=>{const c=cmg.codigo;c.value='console.log("CM QA");\nawait esperar(0.1);';c.setSelectionRange(0,0);c.dispatchEvent(new Event("input"));});
      const antes = await page.evaluate(()=>cmg.codigo.value);
      await page.locator('.cm-content').focus(); await page.keyboard.press("Control+End"); await page.keyboard.press("Enter"); await page.keyboard.type("// final");
      eq(await page.evaluate(()=>cmg.codigo.value.endsWith("// final")),true,serie+": escritura integrada");
      await page.evaluate(()=>cmg.edicion.deshacer());
      eq(await page.evaluate(()=>cmg.codigo.value.endsWith("// final")),false,serie+": deshacer integrado");
      await page.evaluate(()=>__banco.ejecutar());
      await page.waitForFunction(()=>document.querySelector('#consola').textContent.includes('CM QA'));
      eq(await page.evaluate(()=>cmg.ejecutando),true,serie+": Worker ejecuta el texto original");
      eq(await page.locator('.cm-content').getAttribute('contenteditable'),"false",serie+": ejecución bloquea escritura");
      await page.evaluate(()=>cmg.alternarEjecucion());
      eq(await page.locator('.cm-content').getAttribute('contenteditable'),"true",serie+": detener permite escribir");
      await page.reload(); await page.waitForFunction(()=>window.__juegoListo);
      eq(await page.evaluate(()=>cmg.codigo.value.startsWith('console.log("CM QA");')),true,serie+": guardado sobrevive a recarga");
      await page.locator('#b-revisar').click();
      await page.waitForFunction(()=>!!window.__revisionJuego?.vista);
      eq(await page.locator('.cm-editor').count(),1,serie+": revisión conserva instancia del editor");
      await page.screenshot({path:'/workspace/work/codemirror-'+serie+'-movil.png'});
    }
    eq(errores,[],"sin errores JavaScript del navegador");
    eq(externas.filter(u=>!u.includes('netlify')),[],"editor y lenguajes sin CDN");
    console.log(checks+" comprobaciones CodeMirror correctas (Chromium; Android físico pendiente).");
  } finally { await context.close(); await browser.close(); }
}
ejecutar().catch(e=>{console.error(e);process.exitCode=1;});
