import assert from 'node:assert/strict';
// Page de Playwright, puerto de QA dedicado. Incluye ratón y toque emulado.
export async function probarEstudio(page, base='http://127.0.0.1:8771') {
  let comprobaciones=0;
  const verificar=(v,m)=>{assert.ok(v,m);comprobaciones++;};
  const errores=[];page.on('pageerror',e=>errores.push(e.message));
  const estado=()=>page.evaluate(()=>CMGTerreno.serializar(__terreno.mapa));
  const pulsar=async(x,z,y)=>{const p=await page.evaluate(([x,z,y])=>__terreno.proyectar(x,z,y),[x,z,y]);await page.mouse.click(p.x,p.y);};
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/herramientas/terreno/?motor=webgl');await page.waitForFunction(()=>window.__terreno?.listo);
  await page.evaluate(()=>localStorage.clear());await page.reload();await page.waitForFunction(()=>window.__terreno?.listo);
  console.log('Estudio: extensión');
  const inicial=await estado();await page.locator('#tamano summary').click();
  await page.locator('[data-extension="8"]').click();
  verificar(await page.evaluate(()=>__terreno.mapa.columnas===145&&__terreno.mapa.filas===113),'ampliación por franja');
  const ampliado=await estado();await page.locator('#deshacer').click();verificar(await estado()===inicial,'deshacer tamaño exacto');
  await page.locator('#rehacer').click();verificar(await estado()===ampliado,'rehacer tamaño exacto');
  await page.locator('[data-extension="-8"]').click();
  await page.locator('#resolucion').selectOption('0.25');await page.locator('#redimensionar').click();
  verificar(await page.evaluate(()=>__terreno.mapa.columnas===257&&__terreno.mapa.filas===193),'resolución fina');
  await page.locator('#deshacer').click();await page.locator('#tamano summary').click();
  console.log('Estudio: punto preciso y colina elevada');
  await page.locator('#precision summary').click();
  for(const [e,v] of [['x',-8],['y',12.125],['z',-8]]) await page.locator('#punto-'+e).fill(String(v));
  await page.locator('#aplicar-punto').click();
  verificar(await page.evaluate(()=>CMGTerreno.alturaEn(__terreno.mapa,-8,-8)===12.125),'altura exacta');
  await page.locator('#precision summary').click();await page.locator('#cenital').click();await page.waitForTimeout(400);
  await page.locator('[data-material="3"]').click();const pesos=await page.evaluate(()=>JSON.stringify(__terreno.mapa.pesos));
  await pulsar(-8,-8);
  verificar(await page.evaluate(()=>JSON.stringify(__terreno.mapa.pesos))!==pesos,'pintura sobre relieve elevado');
  console.log('Estudio: bloques y pintura elevada');
  await page.locator('#modo-bloques').click();await page.locator('[data-bloque-crear="caja"]').click();
  for(const [i,v] of [16,8,9].entries()) await page.locator('[data-bloques-posicion] input').nth(i).fill(String(v));
  await page.locator('[data-bloques-aplicar-objeto]').click();
  await page.locator('[data-bloques-paso]').fill('0.125');await page.locator('[data-mover-eje="0"][data-signo="1"]').click();
  verificar(await page.evaluate(()=>__terreno.mapa.bloques[0].posicion[0]===16.125),'movimiento preciso X');
  await page.locator('#modo-terreno').click();await page.locator('[data-material="1"]').click();
  const antesPintar=await estado();await pulsar(16,9,12);
  verificar(await page.evaluate(()=>__terreno.mapa.bloques[0].coloresCaras?.some(c=>c!==__terreno.mapa.bloques[0].color)),'pintura sobre caja elevada');
  const pintado=await estado();
  verificar(JSON.stringify(JSON.parse(pintado).pesos)===JSON.stringify(JSON.parse(antesPintar).pesos),'pintar bloque no atraviesa al suelo');
  await page.locator('#deshacer').click();verificar(await estado()===antesPintar,'deshacer pintura elevada');
  await page.locator('#rehacer').click();verificar(await estado()===pintado,'rehacer pintura elevada');
  await page.waitForFunction(()=>localStorage.getItem(CMGTerreno.CLAVE_BORRADOR)===CMGTerreno.serializar(__terreno.mapa));
  await page.reload();await page.waitForFunction(()=>window.__terreno?.listo);verificar(await estado()===pintado,'recarga conserva colores y v3');
  await page.locator('#abrir-archivo').click();const descarga=page.waitForEvent('download');await page.locator('#json').click();
  const d=await descarga, stream=await d.createReadStream(), datos=[];for await(const parte of stream) datos.push(parte);
  verificar(Buffer.concat(datos).toString()===pintado,'JSON descargado conserva pintura');
  // War debe aceptar también la nueva cuadrícula y los colores de caras.
  await page.locator('#abrir-archivo').click();await page.locator('#tamano summary').click();await page.locator('[data-extension="8"]').click();
  const popup=page.waitForEvent('popup');await page.locator('#probar').click();const war=await popup;
  war.on('pageerror',e=>errores.push(e.message));await war.waitForFunction(()=>window.__juegoListo);
  verificar(true,'War abre mapa v3 con extensión y pintura');await war.close();
  console.log('Estudio: smartphone');
  await page.setViewportSize({width:390,height:844});await page.reload();await page.waitForFunction(()=>window.__terreno?.listo);
  verificar(await page.locator('#inspector').isHidden(),'inspector móvil empieza plegado');
  verificar(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth&&document.documentElement.scrollHeight===innerHeight),'visor móvil sin scroll de página');
  await page.locator('#ajustes-toggle').click();verificar(await page.locator('#inspector').isVisible(),'ajustes accesibles en móvil');
  await page.locator('[data-material="4"]').click();await page.locator('#cerrar-ajustes').click();await page.locator('#cenital').click();await page.waitForTimeout(400);
  const cdp=await page.context().newCDPSession(page);
  const punto=await page.evaluate(()=>__terreno.proyectar(6,9));
  const antesAgua=await page.evaluate(()=>JSON.stringify(__terreno.mapa.agua.mascara));
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:punto.x,y:punto.y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  verificar(await page.evaluate(()=>JSON.stringify(__terreno.mapa.agua.mascara))!==antesAgua,'toque emulado pinta agua');
  const antesCamara=await estado();await page.locator('#navegar').click();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:150,y:350}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:190,y:370}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  verificar(await estado()===antesCamara,'navegación táctil no pinta');await cdp.detach();
  await page.setViewportSize({width:844,height:390});verificar(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'horizontal sin desbordamiento');
  verificar(errores.length===0,'sin excepciones: '+errores.join('; '));
  return {comprobaciones};
}
