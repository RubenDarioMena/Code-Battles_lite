// Extensión de QA para las herramientas que Factory comparte con War. Solo origen 8771.
import assert from 'node:assert/strict';
export async function probarFactoryEditor(page, origen = 'http://127.0.0.1:8771') {
  let checks = 0;
  const eq = (a, b, msg) => { assert.deepEqual(a, b, msg); console.log(`OK ${++checks}: ${msg}`); };
  const evaluar = fn => page.evaluate(fn);
  const url = `${origen}/Prototypes/Tres%20vistas/?forma=escritorio`;
  await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1366, height: 768, deviceScaleFactor: 1, mobile: false });
  await page.goto(url);
  await page.waitForFunction(() => !!window.cmg?.edicion);
  await evaluar(() => { window.cmg.edicion.activar(false); window.__banco.elegirReto(0); window.__banco.aplicarModo('js'); });
  await page.fill('#codigo', '');
  await page.click('#paleta [data-js="3"]', { button: 'right' });
  await page.click('.variantes .variante[data-v="3"]');
  eq(await evaluar(() => window.cmg.codigo.value), 'break;', 'las variantes de Factory insertan la instrucción elegida');
  await page.fill('#codigo', '');
  await page.click('#b-teclado');
  eq(await evaluar(() => window.cmg.edicion.activo && !document.querySelector('#bloques').hidden), true, 'Factory activa la edición sin teclado');
  await page.click('#paleta [data-js="1"]');
  await page.waitForSelector('.sugerencias:not([hidden]) .sug[data-i]');
  eq(await evaluar(() => document.querySelector('.sugerencias:not([hidden])').textContent.includes('ENT-1')), true, 'las sugerencias usan las bodegas de Factory');
  await page.click('.sugerencias:not([hidden]) .sug[data-i="0"]');
  await page.waitForFunction(() => document.querySelector('.sugerencias:not([hidden])')?.textContent.includes('material'));
  await page.click('.sugerencias:not([hidden]) .sug[data-i="0"]');
  eq(await evaluar(() => window.cmg.codigo.value), 'await yo.recoger("ENT-1", "cobre");', 'elegir valores rellena origen y material');
  eq(await evaluar(() => document.activeElement !== window.cmg.codigo), true, 'insertar y elegir no enfoca el textarea sin teclado');
  await page.click('#paleta [data-js="0"]');
  eq(await evaluar(() => document.activeElement !== window.cmg.codigo && window.cmg.codigo.value.startsWith('// ')), true, 'comentar tampoco abre el teclado');
  await page.click('#edicion [data-accion="deshacer"]');
  await page.click('#bloques .str >> nth=1');
  eq(await evaluar(() => window.cmg.codigo.value.slice(window.cmg.codigo.selectionStart, window.cmg.codigo.selectionEnd)), '"cobre"', 'un clic selecciona el material con sus comillas');
  await page.click('#edicion [data-accion="borrar"]');
  eq(await evaluar(() => window.cmg.codigo.value), 'await yo.recoger("ENT-1", /* material */);', 'borrar un argumento deja su hueco de material');
  await page.click('#edicion [data-accion="deshacer"]');
  eq(await evaluar(() => window.cmg.codigo.value), 'await yo.recoger("ENT-1", "cobre");', 'deshacer restaura el argumento');
  await page.click('#edicion [data-accion="rehacer"]');
  eq(await evaluar(() => window.cmg.codigo.value.includes('/* material */')), true, 'rehacer recupera la edición');
  await page.click('#edicion [data-accion="deshacer"]');
  await page.click('#b-teclado');
  await page.fill('#codigo', 'await yo.entregar("FUN");');
  await page.click('#modos [data-modo="bloques"]');
  const antes = await evaluar(() => window.__banco.generar(window.__banco.programa.modelo).codigo);
  await page.click('#paleta [data-ladrillo="recoger"]');
  eq(await evaluar(() => window.__banco.programa.modelo.cuerpo.length), 2, 'la paleta de bloques mantiene su modelo');
  await page.click('#edicion [data-accion="deshacer"]');
  eq(await evaluar(() => window.__banco.generar(window.__banco.programa.modelo).codigo), antes, 'deshacer recupera árbol y texto juntos');
  await page.click('#edicion [data-accion="rehacer"]');
  eq(await evaluar(() => window.__banco.programa.modelo.cuerpo.length), 2, 'rehacer restaura el árbol de bloques');
  await page.click('#prog .fila.simple >> nth=0');
  await page.click('#edicion [data-accion="copiar"]');
  await page.click('#modos [data-modo="pseudo"]');
  await page.click('#edicion [data-accion="pegar"]');
  eq(await evaluar(() => window.__banco.programa.modelo.cuerpo.length), 3, 'copiar y pegar bloques funciona entre vistas');
  await page.click('#edicion [data-accion="cortar"]');
  eq(await evaluar(() => window.__banco.programa.modelo.cuerpo.length), 2, 'cortar actúa sobre el bloque elegido');
  await page.click('#edicion [data-accion="deshacer"]');
  eq(await evaluar(() => window.__banco.programa.modelo.cuerpo.length), 3, 'deshacer también recupera un bloque cortado');
  await page.click('#modos [data-modo="js"]');
  await page.fill('#codigo', 'await yo.esperar(2);');
  await page.click('#b-teclado');
  await evaluar(() => window.__banco.elegirReto(1));
  await evaluar(() => window.__banco.elegirReto(0));
  eq(await evaluar(() => window.cmg.codigo.value), 'await yo.esperar(2);', 'cambiar de reto inmediatamente conserva el texto');
  await page.click('#edicion [data-accion="deshacer"]');
  eq(await evaluar(() => window.cmg.codigo.value !== 'await yo.esperar(2);'), true, 'cada reto conserva su historial al regresar');
  await page.click('#edicion [data-accion="rehacer"]');
  eq(await evaluar(() => window.cmg.codigo.value), 'await yo.esperar(2);', 'rehacer pertenece al mismo reto');
  await page.click('#b-ajustes'); await page.selectOption('#ajustes-asa', 'borde');
  await page.click('#ajustes-orden-barra');
  const centro = s => page.evaluate(s => { const r = document.querySelector(s).getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; }, s);
  const de = await centro('#orden-grupos .orden-btn[data-id="borrar"]'), a = await centro('#orden-grupos .orden-btn[data-id="deshacer"]');
  await page.mouse.move(de.x, de.y); await page.mouse.down(); await page.mouse.move(a.x - 25, a.y, { steps: 8 }); await page.mouse.up();
  eq(await evaluar(() => JSON.parse(localStorage.getItem('cmg-banco02-ui-barra'))[1]), ['borrar', 'deshacer', 'rehacer'], 'Factory guarda el orden de barra en su propio espacio');
  await page.click('#orden-restaurar'); await page.click('#orden-cerrar'); await page.click('#ajustes-cerrar');
  await page.reload(); await page.waitForFunction(() => !!window.cmg?.edicion);
  eq(await evaluar(() => window.cmg.edicion.activo && document.querySelector('#editor').dataset.asa === 'borde' && !document.querySelector('#asas').hidden), true, 'modo sin teclado y asas persisten al recargar');
  await page.cdp('Emulation.setDeviceMetricsOverride', { width: 393, height: 852, deviceScaleFactor: 1, mobile: true });
  await page.goto(`${origen}/Prototypes/Tres%20vistas/?forma=movil&marco=1`);
  await page.waitForFunction(() => !!window.cmg?.edicion);
  eq(await evaluar(() => {
    const barra = document.querySelector('#edicion'), paleta = document.querySelector('#paleta');
    return barra.getBoundingClientRect().height < 50 && paleta.getBoundingClientRect().height < 60 && getComputedStyle(document.querySelector('#consola')).display === 'none';
  }), true, 'móvil tiene barras de una línea y consola cerrada');
  await page.click('#edicion [data-accion="teclado"]');
  await page.fill('#codigo', 'await yo.esperar(3);');
  await page.goto(`${origen}/`);
  await page.goto(`${origen}/Prototypes/Tres%20vistas/?forma=movil&marco=1`);
  await page.waitForFunction(() => !!window.cmg?.edicion);
  eq(await evaluar(() => window.cmg.codigo.value), 'await yo.esperar(3);', 'volver al inicio inmediatamente conserva la última edición');
  await page.cdp('Emulation.clearDeviceMetricsOverride');
  console.log(`${checks} comprobaciones del editor Factory correctas`);
  return checks;
}
